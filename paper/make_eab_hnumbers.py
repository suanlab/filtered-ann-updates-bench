#!/usr/bin/env python3
"""Generate paper/eab_hnumbers.tex: LaTeX macros for the follow-up experiments (H1-H8) from
results/bench_h_summary.json (bench/analyze_h.py). Every scalar leaf becomes \\V{h/<path>}, with the path made of
the JSON keys joined by '/', list positions as indices. Numbers are formatted by magnitude; macros whose source is
missing simply do not exist, so the paper shows ??<key> in red until the experiment has run."""
import json, math, sys

def fmt(v):
    if isinstance(v, bool): return 'yes' if v else 'no'
    if isinstance(v, int): return f'{v:,}'
    if not isinstance(v, float) or math.isnan(v) or math.isinf(v): return None
    a = abs(v)
    if a >= 100: return f'{v:,.0f}'
    if a >= 10: return f'{v:.1f}'
    if a >= 1: return f'{v:.2f}'
    if a >= 0.01: return f'{v:.3f}'
    if a == 0: return '0'
    m, e = f'{v:.1e}'.split('e'); return f'{float(m):.1f}\\times10^{{{int(e)}}}'

def walk(x, path, out):
    if isinstance(x, dict):
        for k, v in x.items(): walk(v, path + [str(k)], out)
    elif isinstance(x, list):
        for i, v in enumerate(x): walk(v, path + [str(i)], out)
    else:
        key = 'h/' + '/'.join(path)
        pct = isinstance(x, float) and any(t in key for t in ('rel_err', '/share/', 'regret', 'qps_change', '_frac'))
        f = (f'{100 * x:.0f}\\%' if pct else f'{x:.2f}' if isinstance(x, float) and ('exponent' in key or '/a_n' in key or '/b_s' in key) else fmt(x))
        if pct: out[key + '_pct'] = f'{100 * x:.0f}'
        if f is not None: out[key] = f

S = json.load(open('results/bench_h_summary.json')); out = {}
walk(S, [], out)
with open('paper/eab_hnumbers.tex', 'w') as fo:
    fo.write('% generated by paper/make_eab_hnumbers.py from results/bench_h_summary.json -- do not edit\n')
    for k, v in sorted(out.items()):
        if any(c in k for c in '\\{}%#'): continue
        fo.write('\\expandafter\\def\\csname v@' + k + '\\endcsname{' + v + '}\n')
print(len(out), 'follow-up macros written to paper/eab_hnumbers.tex')

# ---- multi-threaded throughput (results/bench_mt28): QPS at recall targets and scaling over 1 thread ----
import glob, sys
sys.path.insert(0, 'bench'); from analyze import frontier, qps_at, break_even
mt = {}
MTR = {}      # (ds, sc, m) -> {param: best record} over both modes (batch, pool) and both passes
for f in glob.glob('results/bench_mt28*/*/*/*.json'):
    ds, sc, m = f.split('/')[-3], f.split('/')[-2], f.split('/')[-1][:-5]
    for r in json.load(open(f)):
        cur = MTR.setdefault((ds, sc, m), {}).get(r['param'] + '|' + str(round(r['recall'], 4)))
        if cur is None or r['qps']['mean'] > cur['qps']['mean']: MTR[(ds, sc, m)][r['param'] + '|' + str(round(r['recall'], 4))] = r
# same-session single-thread references (results/bench_mt1ref*): the scaling factor is formed within one session
REF = {}
for f in glob.glob('results/bench_mt1ref*/*/*/*.json'):
    ds, sc, m = f.split('/')[-3], f.split('/')[-2], f.split('/')[-1][:-5]
    for r in json.load(open(f)):
        k = r['param'] + '|' + str(round(r['recall'], 4)); cur = REF.setdefault((ds, sc, m), {}).get(k)
        if cur is None or r['qps']['mean'] > cur['qps']['mean']: REF[(ds, sc, m)][k] = r
REFF = {k: frontier([(r['recall'], r['qps']['mean']) for r in v.values()]) for k, v in REF.items()}
for (ds, sc, m), byp in MTR.items():
    recs = list(byp.values()); fr = frontier([(r['recall'], r['qps']['mean']) for r in recs])
    for t in ('0.95', '0.99'):
        v = qps_at(fr, float(t)); mt[f'mt/{ds}/{sc}/{m}/q{t}'] = q(v)
        one = qps_at(REFF[(ds, sc, m)], float(t)) if (ds, sc, m) in REFF else None
        mt[f'mt/{ds}/{sc}/{m}/q{t}_1t'] = q(one)
        mt[f'mt/{ds}/{sc}/{m}/x{t}'] = (f'{v / one:.1f}' + r'$\times$') if (v and one) else '---'
with open('paper/eab_numbers.tex', 'a') as fo:
    for k, v in sorted(mt.items()):
        fo.write('\\expandafter\\def\\csname v@' + k + '\\endcsname{' + v + '}\n')

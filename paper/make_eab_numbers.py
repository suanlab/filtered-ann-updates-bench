#!/usr/bin/env python3
"""Generate paper/eab_numbers.tex: every number quoted in paper_eab.tex is a macro \\V{key} defined here
from results/bench_summary.json, so re-running the benchmark cannot leave stale numbers in the text
(a missing key renders as a red '??key').  Keys:
  <ds>/<schema>/<method>/q<target>      QPS at recall target (e.g. q0.99), or 'n/r' if never reached
  <ds>/<schema>/<method>/maxr           max recall in the sweep
  <ds>/<schema>/<method>/build          build seconds;  .../gb  index bytes in GB
  disp/<ds>/<schema>/<method>/q<t>      oracle-dispatcher QPS at target; .../T<t> threshold; .../p<t> parameter
  bucket/<ds>/<schema>/<method>/<lo>/r  per-bucket recall of the method's best-recall setting; .../q bucket QPS
  stream/<name>/<method>/r<round>/q<t>  stream QPS at target; .../maxr; .../maint (cumulative s); .../gb; .../res
  stream/<name>/<method>/totalmaint      cumulative maintenance at the last round"""
import json, sys
sys.path.insert(0, 'bench')
from analyze import frontier, qps_at, break_even
from common import admissible_sizes, stream_stats

S = json.load(open('results/bench_summary.json')); out = {}
def q(v): return 'n/r' if v is None else (f'{v:,.0f}' if v >= 10 else f'{v:.1f}')
def r3(v): return f'{v:.3f}'
for wl, ms in S['static'].items():
    for m, d in ms.items():
        for t in ('0.9', '0.95', '0.99'): out[f'{wl}/{m}/q{t}'] = q(d.get(f'qps@{t}'))
        out[f'{wl}/{m}/maxr'] = r3(d['max_recall'])
        if d.get('build_s') is not None: out[f'{wl}/{m}/build'] = f"{d['build_s']:,.0f}"
        if d.get('bytes'): out[f'{wl}/{m}/gb'] = f"{d['bytes'] / 1e9:.1f}"
for wl, ms in S['dispatch'].items():
    for m, d in ms.items():
        for t in ('0.9', '0.95', '0.99'):
            b = d.get('best', {}).get(t)
            out[f'disp/{wl}/{m}/q{t}'] = q(b['qps'] if b else None)
            if b: out[f'disp/{wl}/{m}/T{t}'] = f"{b['T']:,}"; out[f'disp/{wl}/{m}/p{t}'] = b['param'].replace("k'", "$k'$")
for wl, ms in S['buckets'].items():
    for m, rows in ms.items():
        best = max(rows, key=lambda r: sum(v['recall'] * v['n'] for k, v in r.items() if k != 'param'))
        for k, v in best.items():
            if k == 'param': continue
            lo = k.split('-')[0]; out[f'bucket/{wl}/{m}/{lo}/r'] = r3(v['recall']); out[f'bucket/{wl}/{m}/{lo}/q'] = q(v['qps'])
            out[f'bucket/{wl}/{m}/{lo}/n'] = str(v['n'])
for name, ms in S['streams'].items():
    for m, d in ms.items():
        for row in d['rounds']:
            p = f"stream/{name}/{m}/r{row['round']}"
            for t in ('0.9', '0.95', '0.99'): out[f'{p}/q{t}'] = q(row.get(f'qps@{t}'))
            out[f'{p}/maxr'] = r3(row['max_recall'])
            mt = row['cum_maint_s'] if row.get('cum_maint_s') is not None else row.get('rebuild_s')
            if mt is not None: out[f'{p}/maint'] = f'{mt:,.1f}'
            if row.get('bytes'): out[f'{p}/gb'] = f"{row['bytes'] / 1e9:.2f}"
            if row.get('resident'): out[f'{p}/res'] = f"{row['resident'] / 1e6:.2f}M"
        if d.get('total_maint_s') is not None: out[f'stream/{name}/{m}/totalmaint'] = f"{d['total_maint_s']:,.1f}"
with open('paper/eab_numbers.tex', 'w') as f:
    f.write('% generated by paper/make_eab_numbers.py from results/bench_summary.json -- do not edit\n')
    for k, v in sorted(out.items()):
        f.write('\\expandafter\\def\\csname v@' + k + '\\endcsname{' + v + '}\n')
print(len(out), 'numbers written')

# ---- derived stream/cost numbers (formulas stated in Section 6 of the paper) ----
import numpy as np
ST = S['streams']; meta = {n: stream_stats(n) for n in ST}
extra = {}
for nm, ms in ST.items():
    R = meta[nm]['R']; nq = meta[nm]['nq']
    U = meta[nm]['updates_per_round']
    extra[f'stream/{nm}/updates_per_round'] = f'{U:,.0f}'
    ivf_m = ms.get('ivf', {}).get('total_maint_s')
    if not ivf_m: print('warning: no IVF maintenance for stream', nm, '- ratios to IVF skipped')
    if 'fdiskann_rebuild' in ms and ivf_m:
        reb = float(np.mean([r['rebuild_s'] for r in ms['fdiskann_rebuild']['rounds']]))
        extra[f'stream/{nm}/fdiskann_rebuild/fresh'] = f'{R * reb:,.0f}'
        extra[f'stream/{nm}/fdiskann_rebuild/perrebuild'] = f'{reb:,.0f}'
        extra[f'stream/{nm}/fdiskann_rebuild/x_ivf'] = f'{R * reb / ivf_m:,.0f}'
        # break-even: fresh F-DiskANN (one rebuild per round) vs IVF at recall 0.95, last round
        qf = ms['fdiskann_rebuild']['rounds'][-1].get('qps@0.95'); qi = ms['ivf']['rounds'][-1].get('qps@0.95')
        Qstar = break_even(reb, ivf_m / R, qi, qf)
        if Qstar is not None:
            dt = 1 / qi - 1 / qf
            extra[f'cost/{nm}/fd_vs_ivf/queries_per_round'] = f'{Qstar:,.0f}'
            extra[f'cost/{nm}/fd_vs_ivf/q_per_update_wall'] = f'{Qstar / U:.1f}'
            extra[f'cost/{nm}/fd_vs_ivf/q_per_update_cpu'] = f'{16 * Qstar / U:.0f}'
            extra[f'cost/{nm}/fd_vs_ivf/ms_saved'] = f'{1000 * dt:.2f}'
    for m, d in ms.items():
        if d.get('total_maint_s') and ivf_m and m != 'ivf': extra[f'stream/{nm}/{m}/x_ivf'] = f"{d['total_maint_s'] / ivf_m:,.0f}"
        rr = d['rounds']
        if rr and rr[0].get('resident') and rr[-1].get('resident'):
            extra[f'stream/{nm}/{m}/res_growth'] = f"{rr[-1]['resident'] / rr[0]['resident']:.1f}"
with open('paper/eab_numbers.tex', 'a') as f:
    for k, v in sorted(extra.items()):
        f.write('\\expandafter\\def\\csname v@' + k + '\\endcsname{' + v + '}\n')
print(len(extra), 'derived numbers appended')

